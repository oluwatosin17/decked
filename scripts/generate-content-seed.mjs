import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { createServer } from 'vite'

const OUTPUT = resolve('supabase/migrations/20261009301000_seed_all_bundled_content.sql')
const normalize = value => String(value).normalize('NFKC').toLowerCase().replace(/[’‘]/g, "'").replace(/[^a-z0-9']+/g, ' ').trim()
const uuid = value => {
  const hex = createHash('sha256').update(value).digest('hex').slice(0, 32).split('')
  hex[12] = '5'
  hex[16] = ((parseInt(hex[16], 16) & 3) | 8).toString(16)
  return `${hex.slice(0,8).join('')}-${hex.slice(8,12).join('')}-${hex.slice(12,16).join('')}-${hex.slice(16,20).join('')}-${hex.slice(20).join('')}`
}
const literal = value => `'${String(value).replaceAll("'", "''")}'`
const jsonLiteral = value => `${literal(JSON.stringify(value))}::jsonb`
const kindFor = gameId => gameId === 'choose-your-side' ? 'choice' : gameId === 'charades' ? 'challenge' : gameId === 'red-flag-green-flag' ? 'scenario' : ['you-laugh','do-or-drink'].includes(gameId) ? 'challenge' : 'prompt'

const server = await createServer({ appType: 'custom', logLevel: 'silent', server: { middlewareMode: true, hmr: false } })
try {
  const { CONTENT_AUDIT_GAMES } = await server.ssrLoadModule('/src/content/deckRegistry.ts')
  const bundledGames = CONTENT_AUDIT_GAMES.filter(game => game.contentModel === 'bundled')
  const categories = []
  const itemMap = new Map()
  const memberships = []

  for (const game of bundledGames) {
    for (const [categoryIndex, deck] of game.decks.entries()) {
      categories.push({ gameId: game.gameId, categoryId: deck.category, label: deck.category.replaceAll('-', ' ').replaceAll('/', ' / '), order: categoryIndex })
      for (const [index, bodyValue] of deck.prompts.entries()) {
        const body = String(bodyValue).trim()
        const key = `${game.gameId}\u0000${normalize(body)}`
        const id = uuid(`decked-content-item-v1\u0000${key}`)
        if (!itemMap.has(key)) {
          const metadata = game.gameId === 'choose-your-side'
            ? (() => { const marker = body.indexOf(' OR '); return marker < 0 ? {} : { option_a: body.slice(0, marker), option_b: body.slice(marker + 4) } })()
            : {}
          itemMap.set(key, { id, gameId: game.gameId, kind: kindFor(game.gameId), body, normalized: normalize(body), metadata, sourceRef: `${game.gameId}:${deck.category}:${index}` })
        }
        memberships.push({ id, gameId: game.gameId, categoryId: deck.category, order: index })
      }
    }
  }

  const items = [...itemMap.values()]
  const gameReleases = bundledGames.map(game => {
    const gameItems = items.filter(item => item.gameId === game.gameId).sort((a,b) => a.id.localeCompare(b.id))
    const gameMemberships = memberships.filter(item => item.gameId === game.gameId)
    const checksum = createHash('sha256').update(gameItems.map(item => `${item.id}:1`).join('\n')).digest('hex')
    return { id: uuid(`decked-content-release-v1\u0000${game.gameId}\u0000${checksum}`), gameId: game.gameId, checksum, itemCount: gameItems.length, membershipCount: gameMemberships.length, items: gameItems.map(item => ({id:item.id,categories:[...new Set(gameMemberships.filter(membership=>membership.id===item.id).sort((a,b)=>a.order-b.order).map(membership=>membership.categoryId))]})) }
  })

  const lines = [
    '-- Generated by scripts/generate-content-seed.mjs from the audited bundled sources.',
    '-- Idempotent and non-destructive: source arrays remain unchanged as runtime fallback.',
    '',
    'insert into public.content_categories(game_id,category_id,label,target_count,sort_order,enabled) values',
    categories.map(row => `  (${literal(row.gameId)},${literal(row.categoryId)},${literal(row.label)},300,${row.order},true)`).join(',\n'),
    'on conflict(game_id,category_id) do update set label=excluded.label,target_count=excluded.target_count,sort_order=excluded.sort_order,updated_at=now();',
    '',
  ]

  for (let start = 0; start < items.length; start += 500) {
    const chunk = items.slice(start, start + 500)
    lines.push('insert into public.content_items(id,game_id,item_kind,lifecycle_status,current_version,published_version,source,source_ref) values')
    lines.push(chunk.map(row => `  (${literal(row.id)}::uuid,${literal(row.gameId)},${literal(row.kind)},'active',1,1,'bundled_import',${literal(row.sourceRef)})`).join(',\n'))
    lines.push('on conflict(id) do nothing;\n')
    lines.push('insert into public.content_item_versions(item_id,version,body,normalized_body,metadata,editorial_status,change_note) values')
    lines.push(chunk.map(row => `  (${literal(row.id)}::uuid,1,${literal(row.body)},${literal(row.normalized)},${jsonLiteral(row.metadata)},'published','Initial deterministic bundled-content import')`).join(',\n'))
    lines.push('on conflict(item_id,version) do nothing;\n')
  }

  for (let start = 0; start < memberships.length; start += 1000) {
    const chunk = memberships.slice(start, start + 1000)
    lines.push('insert into public.content_item_categories(item_id,game_id,category_id,sort_order,enabled) values')
    lines.push(chunk.map(row => `  (${literal(row.id)}::uuid,${literal(row.gameId)},${literal(row.categoryId)},${row.order},true)`).join(',\n'))
    lines.push('on conflict(item_id,game_id,category_id) do update set sort_order=excluded.sort_order,enabled=true;\n')
  }

  lines.push('insert into public.content_releases(id,game_id,status,item_count,membership_count,checksum,notes,published_at) values')
  lines.push(gameReleases.map(row => `  (${literal(row.id)}::uuid,${literal(row.gameId)},'published',${row.itemCount},${row.membershipCount},${literal(row.checksum)},'Initial bundled-content migration',now())`).join(',\n'))
  lines.push('on conflict(id) do nothing;\n')
  for (const release of gameReleases) {
    for (let start = 0; start < release.items.length; start += 1000) {
      lines.push('insert into public.content_release_items(release_id,item_id,version,category_ids) values')
      lines.push(release.items.slice(start,start+1000).map(item => `  (${literal(release.id)}::uuid,${literal(item.id)}::uuid,1,array[${item.categories.map(literal).join(',')}]::text[])`).join(',\n'))
      lines.push('on conflict(release_id,item_id) do nothing;\n')
    }
  }
  lines.push(`do $$ begin if (select count(*) from public.content_item_categories) < ${memberships.length} then raise exception 'Content seed reconciliation failed: expected at least ${memberships.length} memberships'; end if; end $$;`)
  await writeFile(OUTPUT, `${lines.join('\n')}\n`)
  console.log(`Generated ${OUTPUT}`)
  console.log(`${items.length} unique items; ${memberships.length} memberships; ${categories.length} categories; ${gameReleases.length} releases`)
} finally {
  await server.close()
}
