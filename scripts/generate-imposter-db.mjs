import { writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { createServer } from 'vite'

const output = resolve('supabase/migrations/20261012130000_sync_imposter_catalog.sql')
const q = value => `'${String(value).replaceAll("'", "''")}'`
const server = await createServer({ appType: 'custom', logLevel: 'silent', server: { middlewareMode: true, hmr: false } })
try {
  const { IMPOSTER_WORD_PAIRS } = await server.ssrLoadModule('/src/content/imposter.ts')
  const values = IMPOSTER_WORD_PAIRS.map((pair, index) => `  (${index + 1},${q(pair.category)},${q(pair.regular)},${q(pair.imposter)})`).join(',\n')
  const sql = `-- Generated by scripts/generate-imposter-db.mjs from src/content/imposter.ts.
create table if not exists public.decked_imposter_word_pairs (
  id integer primary key, category text not null, regular_word text not null, imposter_word text not null,
  unique(category,regular_word,imposter_word)
);
alter table public.decked_imposter_word_pairs enable row level security;
revoke all on public.decked_imposter_word_pairs from public,anon,authenticated;
insert into public.decked_imposter_word_pairs(id,category,regular_word,imposter_word) values
${values}
on conflict(id) do update set category=excluded.category,regular_word=excluded.regular_word,imposter_word=excluded.imposter_word;
delete from public.decked_imposter_word_pairs where id>${IMPOSTER_WORD_PAIRS.length};

create or replace function public.decked_start_imposter(p_room_id uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare
  target public.decked_rooms; player_count integer; chosen_imposter uuid;
  chosen_pair public.decked_imposter_word_pairs; next_game integer;
begin
  select * into target from public.decked_rooms where id=p_room_id for update;
  if target.id is null or target.game_id<>'imposter' then raise exception 'This room is not playing Imposter.'; end if;
  if target.host_user_id is distinct from auth.uid() then raise exception 'Only the host can start Imposter.'; end if;
  if target.status='finished' then raise exception 'This room has ended.'; end if;
  if target.status='playing' and not exists(select 1 from public.decked_imposter_games where room_id=p_room_id and phase='results') then raise exception 'The current game is still in progress.'; end if;
  select count(*) into player_count from public.decked_room_players where room_id=p_room_id;
  if player_count not between 3 and 10 then raise exception 'Imposter needs between 3 and 10 players.'; end if;
  select user_id into chosen_imposter from public.decked_room_players where room_id=p_room_id order by random() limit 1;
  select * into chosen_pair from public.decked_imposter_word_pairs order by random() limit 1;
  select coalesce(game_number,0)+1 into next_game from public.decked_imposter_games where room_id=p_room_id;
  next_game:=coalesce(next_game,1);
  delete from public.decked_imposter_votes where room_id=p_room_id;
  delete from public.decked_imposter_assignments where room_id=p_room_id;
  insert into public.decked_imposter_games(room_id,game_number,phase,clue_round,turn_index,category,regular_word,imposter_word,imposter_user_id,accused_user_id,group_won,updated_at)
  values(p_room_id,next_game,'role_reveal',1,0,chosen_pair.category,chosen_pair.regular_word,chosen_pair.imposter_word,chosen_imposter,null,null,now())
  on conflict(room_id) do update set game_number=excluded.game_number,phase='role_reveal',clue_round=1,turn_index=0,category=excluded.category,regular_word=excluded.regular_word,imposter_word=excluded.imposter_word,imposter_user_id=excluded.imposter_user_id,accused_user_id=null,group_won=null,updated_at=now();
  insert into public.decked_imposter_assignments(room_id,user_id,word,is_imposter)
  select p_room_id,p.user_id,case when p.user_id=chosen_imposter then chosen_pair.imposter_word else chosen_pair.regular_word end,p.user_id=chosen_imposter from public.decked_room_players p where p.room_id=p_room_id;
  update public.decked_rooms set status='playing',version=version+1 where id=p_room_id;
end;
$$;
revoke execute on function public.decked_start_imposter(uuid) from public,anon;
grant execute on function public.decked_start_imposter(uuid) to authenticated;
do $$ begin if (select count(*) from public.decked_imposter_word_pairs) <> ${IMPOSTER_WORD_PAIRS.length} then raise exception 'Imposter catalog reconciliation failed'; end if; end $$;
`
  await writeFile(output, sql)
  console.log(`Generated ${output}: ${IMPOSTER_WORD_PAIRS.length} pairs`)
} finally { await server.close() }
